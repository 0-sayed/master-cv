import { readFile, writeFile } from "node:fs/promises";

/** Server derivative of the copy deck; never edit the generated catalog directly. */
export async function generateAuthMail() {
	const deck = JSON.parse(
		await readFile(new URL("../../Planning/context/design/copy-deck.json", import.meta.url), "utf8"),
	) as { entries: Array<{ key: string; messages: Record<string, string> }> };
	const entries = deck.entries.filter(({ key }) =>
		/^email\.(verification|reset|emailChange|passwordResetNotice)\./.test(key),
	);
	const catalog = Object.fromEntries(entries.map(({ key, messages }) => [key, messages]));
	return `// Generated by tooling/locales/generate-auth-mail.ts from the copy deck.\nexport const authMessages = ${JSON.stringify(catalog, null, "\t")} as const;\n`;
}
if (import.meta.main)
	await writeFile(
		new URL("../../packages/email/src/auth-messages.generated.ts", import.meta.url),
		await generateAuthMail(),
	);
