import { readFile, writeFile } from "node:fs/promises";

const deck = JSON.parse(
	await readFile(new URL("../../Planning/context/design/copy-deck.json", import.meta.url), "utf8"),
) as {
	entries: Array<{ key: string; messages: Record<string, string> }>;
};
const path = new URL("../../apps/web/src/features/public-copy.ts", import.meta.url);
const prior = await readFile(path, "utf8");
const keys = new Set([...prior.matchAll(/^\s*"([^"]+)": msg\(/gm)].map((match) => match[1]));
keys.add("privacy.policy.purposeDescription");
const descriptors = [...keys].map((key) => {
	const entry = deck.entries.find((entry) => entry.key === key);
	if (!entry) throw new Error(`Missing public copy: ${key}`);
	return `${JSON.stringify(key)}: msg({message:${JSON.stringify(entry.messages["en-US"])},context:${JSON.stringify(key)}}),`;
});
await writeFile(
	path,
	`// Generated by tooling/locales/generate-public-copy.ts from Planning/context/design/copy-deck.json.
import { i18n } from "@lingui/core";
import { msg } from "@lingui/core/macro";
import { useLingui } from "@lingui/react";
const publicMessages = {
${descriptors.join("\n")}
} as const;
export const getPublicCopy = (key: keyof typeof publicMessages) => i18n._(publicMessages[key]);
export function usePublicCopy() {
	const { i18n } = useLingui();
	return (key: keyof typeof publicMessages) => i18n._(publicMessages[key]);
}
`,
);
