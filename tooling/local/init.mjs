import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { parseEnv } from "node:util";

const marker = "# Generated by pnpm local:init; local synthetic development only.";
const secret = () => randomBytes(32).toString("hex");
const readEnv = (path) => (existsSync(path) ? parseEnv(readFileSync(path, "utf8")) : {});

export function initLocal(root = process.cwd()) {
	const infraPath = join(root, ".env");
	const appPath = join(root, ".env.local");
	if (existsSync(appPath) && !readFileSync(appPath, "utf8").startsWith(marker)) {
		throw new Error(
			"Preserving existing .env.local: move it aside deliberately before generating local configuration.",
		);
	}
	const infra = readEnv(infraPath);
	const previous = readEnv(appPath);
	const ports = {
		PORT: infra.PORT ?? "3000",
		SERVER_PORT: infra.SERVER_PORT ?? "3001",
		EMAIL_PORT: infra.EMAIL_PORT ?? "3002",
		POSTGRES_PORT: infra.POSTGRES_PORT ?? "5432",
	};
	for (const value of Object.values(ports)) {
		if (!/^\d+$/.test(value) || Number(value) < 1024 || Number(value) > 65535) {
			throw new Error("Local ports must be integers between 1024 and 65535.");
		}
	}
	if (new Set(Object.values(ports)).size !== Object.keys(ports).length) {
		throw new Error("Local frontend, backend, email and database ports must be distinct.");
	}
	const password = infra.POSTGRES_PASSWORD || secret();
	if (!existsSync(infraPath)) {
		writeFileSync(infraPath, `${marker}\nPOSTGRES_PASSWORD=${password}\n`, { mode: 0o600, flag: "wx" });
	} else if (!infra.POSTGRES_PASSWORD) {
		throw new Error("Existing .env needs POSTGRES_PASSWORD; it was preserved without changes.");
	}
	const app = {
		...previous,
		...ports,
		APP_URL: `http://localhost:${ports.PORT}`,
		DATABASE_URL: `postgresql://master_cv:${encodeURIComponent(password)}@127.0.0.1:${ports.POSTGRES_PORT}/master_cv`,
		AUTH_SECRET: previous.AUTH_SECRET || secret(),
		ENCRYPTION_SECRET: previous.ENCRYPTION_SECRET || secret(),
		STORAGE_BACKEND: previous.STORAGE_BACKEND || "local",
		LOCAL_STORAGE_PATH: previous.LOCAL_STORAGE_PATH || join(root, "data"),
		DEPLOYMENT_NAMESPACE: `local-${ports.PORT}`,
	};
	writeFileSync(
		appPath,
		`${marker}\n${Object.entries(app)
			.sort(([a], [b]) => a.localeCompare(b))
			.map(([key, value]) => `${key}=${JSON.stringify(value)}`)
			.join("\n")}\n`,
		{ mode: 0o600 },
	);
	chmodSync(infraPath, 0o600);
	chmodSync(appPath, 0o600);
	return app;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	try {
		const app = initLocal();
		console.info(`Local configuration ready: ${app.APP_URL}. Secrets were written to ignored files.`);
	} catch (error) {
		console.error(error.message);
		process.exitCode = 1;
	}
}
