export function assertPersonalDataInventory(tables: Record<string, unknown> = schema) {
	const found = Object.values(tables).filter((value): value is PgTable => is(value, PgTable));
	if (found.length !== Object.keys(personalDataInventory).length) throw new Error("UNMAPPED_SCHEMA_TABLE");
	for (const table of found) {
		const name = getTableConfig(table).name;
		const policy = (personalDataInventory as Record<string, DataClassification>)[name];
		if (!policy) throw new Error("UNMAPPED_SCHEMA_TABLE");
		const classified = [...policy.exportColumns, ...policy.excludedColumns].sort();
		const columns = Object.keys(getTableColumns(table)).sort();
		if (JSON.stringify(classified) !== JSON.stringify(columns)) throw new Error("UNMAPPED_SCHEMA_COLUMN");
	}
}
export function inventoryTable(policy: DataClassification) {
	const table = (schema as Record<string, unknown>)[policy.table];
	if (!is(table, PgTable)) throw new Error("UNMAPPED_SCHEMA_TABLE");
	return table;
}
export function ownerSelector(policy: DataClassification, userId: string): SQL {
	const table = inventoryTable(policy);
	const columns = getTableColumns(table);
	if (policy.owner === "global" || policy.owner === "restricted") throw new Error("RESTRICTED_INVENTORY");
	if (policy.owner === "resume") return sql`${columns.resumeId} IN (SELECT id FROM resume WHERE user_id=${userId})`;
	if (policy.owner === "ownedClient")
		return sql`${columns.clientId} IN (SELECT client_id FROM oauth_client WHERE user_id=${userId} OR reference_id=${userId})`;
	if (policy.owner === "verification")
		return sql`master_cv_verification_owner(${columns.value})=${userId} OR ${columns.identifier} IN (SELECT email FROM "user" WHERE id=${userId}) OR ${columns.identifier} IN (SELECT '2fa-attempts-' || v.identifier FROM verification v WHERE v.value=${userId})`;
	if (policy.table === "oauthClient") return sql`${columns.userId}=${userId} OR ${columns.referenceId}=${userId}`;
	const column = columns[policy.owner];
	if (!column) throw new Error("INVALID_INVENTORY_OWNER");
	return sql`${column}=${userId}`;
}
